-- Recipe dish_type: the "what form is it" browse axis (soup / salad /
-- sandwich / burger ...), independent of `cuisine`. Added because cuisine
-- alone can't answer the question people actually ask when deciding what
-- to eat -- they want a soup, not necessarily a Thai one. See
-- RECIPE_DISH_TYPES in domains/recipes/schema.ts for the vocabulary and
-- the "exactly one, dominant form wins" rule.
--
-- Three steps, in order, so the column can end up NOT NULL without a
-- window where existing rows violate it:
--   1. add nullable + CHECK constraint
--   2. backfill all 270 existing recipes from an explicit name->type map
--   3. set NOT NULL
--
-- The backfill is an explicit per-recipe VALUES list rather than keyword
-- rules on the name. Keyword rules looked tempting but misfile exactly
-- the dishes that matter: "Chicken Tortilla Soup" is a soup not a wrap,
-- "Taco Salad" is a salad not a taco, "Shrimp Scampi with Zucchini
-- Noodles" is pasta not noodles. A literal list is longer but every call
-- is visible in review, which is the point of a migration.

alter table public.recipes
  add column dish_type text;

alter table public.recipes
  add constraint recipes_dish_type_check check (dish_type in (
    'soup','stew','chili','curry',
    'salad',
    'sandwich','burger','wrap','burrito','tacos','pizza',
    'pasta','noodles','rice','bowl',
    'stir_fry','grilled','bbq','casserole','seafood',
    'eggs','pancakes','oatmeal','toast',
    'baked','smoothie','dip','snack_bite'
  ));

