-- Fail loudly rather than silently shipping a half-typed library: if any
-- recipe was added between this migration being written and applied, the
-- NOT NULL below would fail with a generic error. This says why.
do $$
declare missing int;
begin
  select count(*) into missing from public.recipes where dish_type is null;
  if missing > 0 then
    raise exception 'dish_type backfill missed % recipe(s) -- add them to this migration''s VALUES list', missing;
  end if;
end $$;

alter table public.recipes
  alter column dish_type set not null;

-- Browsing is always "this meal type, this dish type" (the picker scopes
-- to a slot before anything else), so the composite matches the real
-- query shape rather than dish_type alone.
create index if not exists recipes_meal_type_dish_type_idx
  on public.recipes (meal_type, dish_type);
